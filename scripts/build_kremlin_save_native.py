"""Reproduce the experimental RUS/ENG autonomous NASM payload for levels 1-3.

No reference game bytes are needed to assemble. This is a development builder,
not runtime code or a registered WASDify patch.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess

from wasdify import kremlin_save_state as state

ROOT = Path(__file__).resolve().parents[1]
PATCHES = ROOT / 'src/wasdify/patches'


def layout_fields(kind, variant):
    fields = dict(state.COMMON)
    if kind == 7:
        fields = {k: v for k, v in fields.items() if k in ('width', 'height')}
    elif variant & 1:
        fields.update(state.ANIMATION)
    fields.update(state.FIELDS.get(kind, {}))
    if not variant & 2:
        names = state.POSE if kind == 8 else (*state.POSE, 'previous_commands',
            'height_min', 'height_max', 'burst_count', 'stride_count') if kind in (1, 5, 9) else ()
        for name in names:
            fields.pop(name, None)
    return fields


def tables():
    layouts, labels, bodies = [], {}, []
    for kind in range(14):
        for variant in range(4):
            fields = layout_fields(kind, variant)
            packed = tuple((offset, struct.calcsize('<' + wire)) for offset, wire in fields.values())
            if packed not in labels:
                label = 'native_fields_' + str(len(labels))
                labels[packed] = label
                bodies += [label + ':', 'dw ' + str(sum(size for _, size in packed)),
                           'db ' + ','.join(str(n) for pair in packed for n in pair) + ',0,0']
            layouts.append(labels[packed])
    messages = json.loads((ROOT / 'src/wasdify/data/kremlin_save_prototype_messages.json').read_text('utf-8'))
    lines = ['; Generated by scripts/build_kremlin_save_native.py; MIT.',
             'native_layouts: dw ' + ','.join(layouts), *bodies]
    for lang in ('ru', 'en'):
        catalog = messages[lang]
        for key, value in catalog.items():
            raw = value.encode('cp866') + b'\0'
            lines += [f'native_{lang}_{key}: db ' + ','.join(str(n) for n in raw)]
        for selected in (0, 1):
            value = catalog['choice_title'] + '\n\n' + '\n'.join(
                ('> ' if i == selected else '  ') + catalog[key]
                for i, key in enumerate(('choice_start', 'choice_load'))) + '\n\n' + catalog['choice_hint']
            lines += [f'native_{lang}_choice_{selected}: db ' + ','.join(str(n) for n in value.encode('cp866') + b'\0')]
    raw = ('\n'.join(lines) + '\n').encode('ascii')
    fingerprint = hashlib.sha256(raw).digest()[:16]
    crc_table = []
    for byte in range(256):
        value = byte
        for _ in range(8):
            value = (value >> 1) ^ (0xedb88320 if value & 1 else 0)
        crc_table.append(value)
    return raw + ('native_schema: db ' + ','.join(str(n) for n in fingerprint) + '\n' +
        'native_crc_table: dd ' + ','.join(hex(n) for n in crc_table) + '\n').encode('ascii')


def build(nasm, output, *, test_gates=False, language='ru'):
    if language not in ('ru', 'en'):
        raise ValueError('native_language_unsupported')
    generated = PATCHES / 'kremlin_save_native_tables.inc'
    expected = tables()
    if generated.read_bytes().replace(b'\r\n', b'\n') != expected:
        raise ValueError('native_tables_stale: run with --tables')
    output.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run([str(nasm), '-f', 'bin', f'-DENG={int(language == "en")}',
                    *(['-DKRS_NATIVE_TEST=1'] if test_gates else []), '-I', str(PATCHES) + '/',
                    str(PATCHES / 'kremlin_save_native.asm'), '-o', str(output)], check=True)
    return hashlib.sha256(output.read_bytes()).hexdigest()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--nasm', type=Path, default=ROOT / 'build/tools/nasm-2.16.03/nasm.exe')
    parser.add_argument('--output', type=Path)
    parser.add_argument('--tables', action='store_true')
    parser.add_argument('--language', choices=('ru', 'en'), default='ru')
    args = parser.parse_args()
    if args.tables:
        (PATCHES / 'kremlin_save_native_tables.inc').write_bytes(tables())
    output = args.output or ROOT / f'build/save-research/native-{args.language}.bin'
    print(build(args.nasm, output, language=args.language))
